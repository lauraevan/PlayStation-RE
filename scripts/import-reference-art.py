#!/usr/bin/env python3
"""Import equivalent publicly available GTA VI promotional images for PlayStation-RE.
The preview also works when these downloads fail, using remote-image fallbacks.
"""
from __future__ import annotations
import io
import json
from pathlib import Path
from urllib.request import Request, urlopen
from PIL import Image, ImageOps, UnidentifiedImageError

ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/"assets"
OUT.mkdir(exist_ok=True)
SOURCES={
    "cover": [
      "https://blog.zh-hant.playstation.com/tachyon/sites/8/2026/06/cd149a81d72b805918215f472544c9b320667327.jpg",
      "https://www.rockstargames.com/VI/_next/static/media/Official_Cover_Art_square.12.uu2irr.2_a.jpg"
    ],
    "logo": [
      "https://crystalpng.com/wp-content/uploads/2025/02/gta-6-logo-03.png",
      "https://www.rockstargames.com/VI/_next/static/media/VIstack.fe9b0515.svg"
    ],
    "hero": [
      "https://www.rockstargames.com/VI/_next/static/media/Jason_and_Lucia_Beach_landscape.0419q._86ukpt.jpg",
      "https://assets.games.gg/gta_6_confirmed_guns_trailers_screenshots_hero_72646daa1c.webp",
    ]
}
FILES={"cover":"gta-vi-cover.jpg","logo":"gta-vi-logo.png","hero":"gta-vi-hero.webp"}
MAX_INPUT=14_000_000
def get_image(url):
    request=Request(url,headers={"User-Agent":"Mozilla/5.0 (compatible; PSRE-asset-import/1.0)","Accept":"image/avif,image/webp,image/png,image/jpeg,image/*;q=0.8"})
    with urlopen(request,timeout=35) as response:
        length=int(response.headers.get("Content-Length","0"))
        if length>MAX_INPUT:raise ValueError("Asset is over 14 MB")
        payload=response.read(MAX_INPUT+1)
    if len(payload)>MAX_INPUT:raise ValueError("Asset is too large")
    img=Image.open(io.BytesIO(payload))
    img.verify()
    return Image.open(io.BytesIO(payload))
def import_image(name, urls):
    target=OUT/FILES[name]
    if target.exists() and target.stat().st_size>1024:
        print("Already present:",target)
        return target
    for url in urls:
        try:
            if url.endswith(".svg"):
                print("Skip vector fallback: needs SVG rasterizer")
                continue
            img=ImageOps.exif_transpose(get_image(url))
            if name=="logo":
                img.thumbnail((1000,800),Image.Resampling.LANCZOS)
                img.convert("RGBA").save(target,format="PNG",optimize=True)
            elif name=="hero":
                img.thumbnail((1920,1080),Image.Resampling.LANCZOS)
                img.convert("RGB").save(target,format="WEBP",quality=87,method=5)
            else:
                img.thumbnail((1200,1200),Image.Resampling.LANCZOS)
                img.convert("RGB").save(target,format="JPEG",quality=88,optimize=True,progressive=True)
            print(name+":",target, target.stat().st_size,"bytes",url)
            return target
        except (OSError,ValueError,UnidentifiedImageError) as e:
            print(name+": failed source",url,str(e))
    print("WARNING:",name,"could not be downloaded; browser will use remote fallback")
    return None
def main():
    results={key:import_image(key,urls) for key,urls in SOURCES.items()}
    mapping={
        key:"./assets/"+file.name
        for key,file in results.items() if file is not None
    }
    (OUT/"local-art.json").write_text(json.dumps(mapping,indent=2)+"\n",encoding="utf-8")
    (OUT/"local-art.js").write_text(
      "// Generated by scripts/import-reference-art.py\nwindow.PSRE_ASSETS = {gta6: "
      +json.dumps(mapping.get("cover","https://blog.zh-hant.playstation.com/tachyon/sites/8/2026/06/cd149a81d72b805918215f472544c9b320667327.jpg"))
      +"};\n",encoding="utf-8")
    print("Imported",len(mapping),"of 3 promotional assets")
if __name__=="__main__":
    main()
